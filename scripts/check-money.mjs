import assert from 'node:assert/strict';
import {parseCents,validDate,totals,validateMovement,cleanCategory,categoryKey} from '../lib/money.ts';
import {distribution,dailyTrend,monthlyTrend,shiftMonth} from '../lib/analysis.ts';
assert.equal(parseCents('0.10'),10);
assert.equal(parseCents('25,50'),2550);
for(const value of ['0','-1','1.234','1e3','NaN','','1000000000'])assert.equal(parseCents(value),null,value);
assert.equal(validDate('2026-02-30'),false);
assert.equal(validDate('2024-02-29'),true);
const expense={id:'12345678-1234-1234-1234-123456789abc',type:'expense',cents:2550,category:'Casa',note:'Prueba',date:'2026-10-01'};
assert.ok(validateMovement(expense));
assert.equal(validateMovement({...expense,cents:1.2}),null);
assert.equal(validateMovement({...expense,type:'transfer'}),null);
assert.equal(validateMovement({...expense,category:'<script>'}),null);
assert.ok(validateMovement({...expense,category:'Personalizada'}));
assert.equal(cleanCategory('  Viajes   familiares '),'Viajes familiares');
assert.equal(categoryKey('Cirugías'),categoryKey('Cirugias'));
assert.equal(cleanCategory('x'.repeat(41)),null);
const rows=[expense,{...expense,type:'income',cents:10000,category:'Consultas'}, {...expense,category:'Anterior',cents:450,date:'2026-10-02'}, {...expense,type:'expense',cents:1000,date:'2026-09-30'}, {...expense,type:'income',cents:12000,date:'2026-09-30'}];
assert.deepEqual(totals(rows.filter(r=>r.date.startsWith('2026-10'))),{expense:3000,income:10000});
const pie=distribution(rows.filter(r=>r.date.startsWith('2026-10')),'expense');
assert.deepEqual(pie.map(d=>[d.name,d.cents,d.percent]),[['Casa',2550,85],['Anterior',450,15]]);
assert.equal(distribution([],'income').length,0);
const daily=dailyTrend(rows,'2026-10');
assert.equal(daily.length,31);assert.equal(daily[0].net,74.5);assert.equal(daily[1].net,70);assert.equal(daily.at(-1).net,70);
assert.equal(dailyTrend([],'2024-02').length,29);
const months=monthlyTrend(rows,'2026-10');assert.equal(months.length,6);assert.equal(months.at(-1).income,100);assert.equal(months.at(-2).expense,10);
assert.equal(shiftMonth('2026-01',-1),'2025-12');assert.equal(shiftMonth('2025-12',1),'2026-01');
console.log('Montos, categorías, distribución, tendencias y acumulado: OK');
